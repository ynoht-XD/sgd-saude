@admin_bp.route("/usuarios")
@admin_required
@require_permission("admin_usuarios", "ver")
def usuarios_listar():
    usuarios = []
    conn = None
    clinica_id = _current_clinica_id()

    try:
        ensure_users_table()

        conn = db_conn(True)

        try:
            conn.rollback()
        except Exception:
            pass

        cur = conn.cursor()

        cur.execute("""
            SELECT
                id,
                nome,
                cpf,
                cpf_digits,
                email,
                role,
                is_active,
                criado_em,
                cbo,
                cbo_descricao,
                clinica_id
              FROM usuarios
             WHERE clinica_id = %s
               AND COALESCE(is_master, FALSE) = FALSE
               AND COALESCE(is_superuser, FALSE) = FALSE
             ORDER BY id DESC;
        """, (clinica_id,))

        rows = _fetchall_as_dicts(cur)

        for r in rows:
            cbo_codigo = (r.get("cbo") or "").strip()
            cbo_descricao = (r.get("cbo_descricao") or "").strip()

            usuarios.append({
                "id": r.get("id"),
                "nome": r.get("nome"),
                "cpf": r.get("cpf"),
                "cpf_digits": r.get("cpf_digits"),
                "email": r.get("email"),
                "role": r.get("role"),
                "is_active": _normalize_bool(r.get("is_active")),
                "criado_em": r.get("criado_em"),
                "cbo": cbo_codigo,
                "cbo_descricao": cbo_descricao,
                "cbo_label": (
                    f"{cbo_codigo} — {cbo_descricao}"
                    if cbo_codigo and cbo_descricao
                    else (cbo_codigo or "—")
                ),
                "clinica_id": r.get("clinica_id"),
            })

        registrar_log(
            modulo="admin_usuarios",
            acao="visualizar",
            entidade="usuarios",
            descricao="Visualizou lista de usuários.",
            detalhes={
                "clinica_id": clinica_id,
                "total": len(usuarios),
            },
        )

    except Exception as e:
        if conn:
            conn.rollback()

        log_erro(
            "admin_usuarios",
            e,
            entidade="usuarios",
            descricao="Falha ao carregar usuários.",
            detalhes={"clinica_id": clinica_id},
        )

