def get_cbo_descricao(codigo: str | None) -> str:
    codigo = only_digits(codigo)[:6]

    if not codigo:
        return ""

    cache_key = f"cbo_desc_{codigo}"

    if hasattr(g, cache_key):
        return getattr(g, cache_key)

    conn = db_conn(True)

    try:
        cur = conn.cursor()

        try:
            cur.execute("""
                SELECT BTRIM(COALESCE(descricao, '')) AS descricao
                  FROM cbo_catalogo
                 WHERE BTRIM(COALESCE(codigo, '')) = %s
                 LIMIT 1;
            """, (codigo,))

            row = _fetchone_as_dict(cur)

            if row and (row.get("descricao") or "").strip():
                desc = row["descricao"].strip()
                setattr(g, cache_key, desc)
                return desc

        except Exception:
            conn.rollback()

        try:
            cur.execute("""
                SELECT BTRIM(COALESCE(no_ocupacao, '')) AS descricao
                  FROM ocupacoes
                 WHERE BTRIM(COALESCE(co_ocupacao, '')) = %s
                 LIMIT 1;
            """, (codigo,))

            row = _fetchone_as_dict(cur)

            desc = (row.get("descricao") or "").strip() if row else ""
            setattr(g, cache_key, desc)
            return desc

        except Exception:
            conn.rollback()
            setattr(g, cache_key, "")
            return ""

    finally:
        conn.close()


def cbo_existe_no_catalogo(codigo: str | None) -> bool:
    codigo = only_digits(codigo)[:6]

    if not codigo:
        return False

    cache_key = f"cbo_existe_{codigo}"

    if hasattr(g, cache_key):
        return getattr(g, cache_key)

    conn = db_conn(True)

    try:
        cur = conn.cursor()

        try:
            cur.execute("""
                SELECT 1
                  FROM cbo_catalogo
                 WHERE BTRIM(COALESCE(codigo, '')) = %s
                 LIMIT 1;
            """, (codigo,))

            if cur.fetchone():
                setattr(g, cache_key, True)
                return True

        except Exception:
            conn.rollback()

        try:
            cur.execute("""
                SELECT 1
                  FROM ocupacoes
                 WHERE BTRIM(COALESCE(co_ocupacao, '')) = %s
                 LIMIT 1;
            """, (codigo,))

            ok = cur.fetchone() is not None
            setattr(g, cache_key, ok)
            return ok

        except Exception:
            conn.rollback()
            setattr(g, cache_key, False)
            return False

    finally:
        conn.close()


def get_cbos_catalogo_local(q: str | None = None, limit: int = 200):
    cache_key = f"cbos_catalogo_{(q or '').strip().lower()}_{limit}"

    if hasattr(g, cache_key):
        return getattr(g, cache_key)

    conn = db_conn(True)

    try:
        cur = conn.cursor()
        q_norm = (q or "").strip()
        q_digits = only_digits(q_norm)

        def montar_items(rows):
            return [
                {
                    "id": (r.get("codigo") or "").strip(),
                    "codigo": (r.get("codigo") or "").strip(),
                    "descricao": (r.get("descricao") or "").strip(),
                    "label": f"{(r.get('codigo') or '').strip()} - {(r.get('descricao') or '').strip()}".strip(" -"),
                }
                for r in rows
                if (r.get("codigo") or "").strip()
            ]

        try:
            sql = """
                SELECT
                    BTRIM(COALESCE(codigo, '')) AS codigo,
                    BTRIM(COALESCE(descricao, '')) AS descricao
                  FROM cbo_catalogo
                 WHERE BTRIM(COALESCE(codigo, '')) <> ''
            """
            params = []

            if q_norm:
                sql += """
                   AND (
                        CAST(codigo AS TEXT) ILIKE %s
                        OR COALESCE(descricao, '') ILIKE %s
                   )
                """
                params.extend([f"%{q_digits or q_norm}%", f"%{q_norm}%"])

            sql += " ORDER BY codigo ASC LIMIT %s;"
            params.append(int(limit))

            cur.execute(sql, params)
            items = montar_items(_fetchall_as_dicts(cur))

            if items:
                setattr(g, cache_key, items)
                return items

        except Exception:
            conn.rollback()

        try:
            sql = """
                SELECT
                    BTRIM(COALESCE(co_ocupacao, '')) AS codigo,
                    BTRIM(COALESCE(no_ocupacao, '')) AS descricao
                  FROM ocupacoes
                 WHERE BTRIM(COALESCE(co_ocupacao, '')) <> ''
            """
            params = []

            if q_norm:
                sql += """
                   AND (
                        CAST(co_ocupacao AS TEXT) ILIKE %s
                        OR COALESCE(no_ocupacao, '') ILIKE %s
                   )
                """
                params.extend([f"%{q_digits or q_norm}%", f"%{q_norm}%"])

            sql += " ORDER BY codigo ASC LIMIT %s;"
            params.append(int(limit))

            cur.execute(sql, params)
            items = montar_items(_fetchall_as_dicts(cur))
            setattr(g, cache_key, items)
            return items

        except Exception:
            conn.rollback()
            setattr(g, cache_key, [])
            return []

    finally:
        conn.close()


